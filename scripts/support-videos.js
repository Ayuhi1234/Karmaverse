// Registers the Earth Buddy FAQ videos you've made in the HeyGen website.
//
//   1. Save each video as public/support-videos/<faq-id>.mp4
//      (faq ids are in backend-support-service/faq/faqs.json, e.g. pickup-schedule.mp4)
//   2. Run: npm run support:videos
//
// This writes src/data/supportVideos.ts, the list the Help & Support screen
// reads to show "Watch video" on those answers. Videos ship with the website
// (public/ is published as-is), so phones stream them instead of the app
// download getting bigger.

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'public', 'support-videos');
const out = path.join(root, 'src', 'data', 'supportVideos.ts');
const faqs = require(path.join(root, 'backend-support-service', 'faq', 'faqs.json'));
const ids = new Set(faqs.map((f) => f.id));
const MAX_MB = 5;

fs.mkdirSync(dir, { recursive: true });
const files = fs.readdirSync(dir).filter((f) => /\.mp4$/i.test(f)).sort();
const ok = [];
for (const file of files) {
  const id = file.replace(/\.mp4$/i, '');
  const mb = fs.statSync(path.join(dir, file)).size / 1048576;
  if (!ids.has(id)) { console.warn(`✖ ${file}: no FAQ has the id "${id}" — rename it to one of the ids in faqs.json`); continue; }
  if (mb > MAX_MB) console.warn(`⚠ ${file} is ${mb.toFixed(1)} MB — please compress it below ${MAX_MB} MB (720p, ~1.5 Mbps) so it loads fast on mobile data`);
  ok.push({ id, file });
  console.log(`✔ ${file} (${mb.toFixed(1)} MB)`);
}

const body = `// Generated by \`npm run support:videos\` — do not edit by hand.
// FAQ id → video file in public/support-videos/.
export const SUPPORT_VIDEOS: Record<string, string> = {
${ok.map(({ id, file }) => `  '${id}': '${file}',`).join('\n')}
};
`;
fs.writeFileSync(out, body);
console.log(`\n${ok.length} video(s) registered in src/data/supportVideos.ts${ok.length < faqs.length ? ` (${faqs.length - ok.length} FAQs still without a video)` : ''}.`);
